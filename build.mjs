#!/usr/bin/env node
/**
 * Concatenates src/*.js into a single installable userscript.
 *   node build.mjs
 */
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, 'src');
const outFile = join(here, 'miri-translate.user.js');

const banner = `/*!
 * MiriTranslator — 웹페이지 번역 (Chrome-style webpage translator)
 * https://github.com/enflip/MiriTranslator-web
 *
 * Keyless engines : Google · Papago · DeepL · MyMemory · Reverso
 * Optional keys   : DeepL API · Microsoft · Papago N2MT · Google Cloud · LibreTranslate · Custom
 *
 * MIT License
 * This file is generated by build.mjs — edit the files in src/ instead.
 */
`;

const files = (await readdir(srcDir))
  .filter((f) => f.endsWith('.js'))
  .sort();

/**
 * CSS lives inside template literals, so a stray backtick in a comment would
 * silently truncate the string and break the script at runtime. Catch that here.
 */
function assertSafeTemplates(name, code) {
  const backticks = (code.match(/`/g) || []).length;
  if (backticks % 2 !== 0) {
    throw new Error(`src/${name}: unbalanced backtick (${backticks} found) — a backtick inside a CSS comment or string breaks the template literal`);
  }
  if (name.endsWith('-css.js')) {
    const withoutComments = code.replace(/\/\*[\s\S]*?\*\//g, '');
    const insideComments = (code.match(/\/\*[\s\S]*?\*\//g) || []).join('');
    if (insideComments.includes('`') || insideComments.includes('${')) {
      throw new Error(`src/${name}: template syntax inside a CSS comment — use plain text in CSS comments`);
    }
    if (/\$\{/.test(withoutComments) && !/\$\{/.test(code)) {
      throw new Error(`src/${name}: template expression outside a template literal`);
    }
  }
}

const parts = [];
for (const file of files) {
  const body = await readFile(join(srcDir, file), 'utf8');
  assertSafeTemplates(file, body);
  parts.push(`/* ==== src/${file} ${'='.repeat(Math.max(0, 58 - file.length))} */\n${body.replace(/\s+$/, '')}\n`);
}

const output = `${banner}\n${parts.join('\n')}`;
await writeFile(outFile, output, 'utf8');

const { size } = await stat(outFile);
const lines = output.split('\n').length;
console.log(`✔ ${files.length} modules -> miri-translate.user.js (${lines} lines, ${(size / 1024).toFixed(1)} KB)`);